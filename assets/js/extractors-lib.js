// ============================================================
//  EXTRACTORS-LIB.JS — shared helpers for the Extractors feature
//  Loaded after extractors-data.js on: index, ioc-feed, extractors
//
//  window.ExtractorStore
//    .all()          published (extractors-data.js) + local (this browser), newest first
//    .unreported()   entries that have no report yet
//    .iocSources()   extractor entries shaped like "reports" so the IOC
//                    feed / charts / home preview can merge them
//    .exportJs()     text of a ready-to-commit extractors-data.js
// ============================================================
(function () {
  var LS_KEY = 'secblog_local_extractors';

  function esc(s) {
    return String(s == null ? '' : s)
      .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;').replace(/'/g, '&#39;');
  }

  function loadLocal() {
    try {
      var v = JSON.parse(localStorage.getItem(LS_KEY) || '[]');
      return Array.isArray(v) ? v : [];
    } catch (e) { return []; }
  }

  function saveLocal(arr) {
    try { localStorage.setItem(LS_KEY, JSON.stringify(arr)); return true; }
    catch (e) { return false; }
  }

  function published() {
    return (typeof EXTRACTORS !== 'undefined' && Array.isArray(EXTRACTORS)) ? EXTRACTORS : [];
  }

  function all() {
    var pub = published().map(function (e) { return Object.assign({}, e, { _local: false }); });
    var pubSlugs = {};
    pub.forEach(function (e) { pubSlugs[e.slug] = true; });
    // a local copy whose slug is already published was committed — hide the local duplicate
    var loc = loadLocal()
      .filter(function (e) { return e && e.slug && !pubSlugs[e.slug]; })
      .map(function (e) { return Object.assign({}, e, { _local: true }); });
    return loc.concat(pub).sort(function (a, b) {
      return (b.date || '').localeCompare(a.date || '');
    });
  }

  function hasReport(e) { return !!(e && e.report); }

  function unreported() {
    return all().filter(function (e) { return !hasReport(e); });
  }

  function iocSources() {
    return all()
      .filter(function (e) { return e.iocs && e.iocs.length; })
      .map(function (e) {
        return {
          slug: e.slug,
          title: e.name,
          date: e.date || '',
          tag: 'EXTRACTOR',
          severity: '',
          href: 'detections.html?tab=extractors#' + e.slug,
          isExtractor: true,
          local: !!e._local,
          iocs: e.iocs.map(function (i) {
            return Object.assign({}, i, { family: i.family || e.family });
          })
        };
      });
  }

  function slugify(s) {
    return String(s || '').toLowerCase().trim()
      .replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 60) || 'extractor';
  }

  function uniqueSlug(base) {
    var taken = {};
    all().forEach(function (e) { taken[e.slug] = true; });
    var slug = base, n = 2;
    while (taken[slug]) { slug = base + '-' + n++; }
    return slug;
  }

  function clean(e) {
    var c = Object.assign({}, e);
    delete c._local;
    return c;
  }

  function exportJs() {
    var entries = all().map(clean);
    var head = [
      '// ============================================================',
      '//  EXTRACTORS-DATA.JS — generated by detections.html on ' + new Date().toISOString().slice(0, 10),
      '//  Replace assets/js/extractors-data.js with this file, then',
      '//  git add, git commit, git push.',
      '//  Set  report: "your-report-slug"  on an entry once its write-up exists.',
      '// ============================================================',
      '',
      'const EXTRACTORS = '
    ].join('\n');
    return head + JSON.stringify(entries, null, 2) + ';\n';
  }

  window.ExtractorStore = {
    LS_KEY: LS_KEY,
    esc: esc,
    loadLocal: loadLocal,
    saveLocal: saveLocal,
    published: published,
    all: all,
    hasReport: hasReport,
    unreported: unreported,
    iocSources: iocSources,
    slugify: slugify,
    uniqueSlug: uniqueSlug,
    exportJs: exportJs
  };
})();
