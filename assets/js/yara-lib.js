// ============================================================
//  YARA-LIB.JS — shared helpers for standalone YARA rules
//  Loaded after yara-data.js on: index, detections
//
//  window.YaraStore
//    .all()          published rules (yara-data.js) + rules added in this browser
//    .count()        how many standalone rules there are
//    .reportCount()  rules written inside reports (yara: [...] in reports-data.js)
//    .total()        reportCount + count — the number the homepage counter shows
//    .exportJs()     text of a ready-to-commit yara-data.js
// ============================================================
(function () {
  // same key the YARA tab has always used, so rules you already added keep working
  var LS_KEY = 'secblog_standalone_yara';

  function slugify(s) {
    return String(s || '').toLowerCase().trim()
      .replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '').slice(0, 60) || 'rule';
  }

  function readRaw() {
    try {
      var v = JSON.parse(localStorage.getItem(LS_KEY) || '[]');
      return Array.isArray(v) ? v : [];
    } catch (e) { return []; }
  }

  function writeRaw(arr) {
    try { localStorage.setItem(LS_KEY, JSON.stringify(arr)); return true; }
    catch (e) { return false; }
  }

  // rules saved before ids existed get a stable id the first time they are read
  function localRaw() {
    var raw = readRaw(), used = {}, dirty = false;
    raw.forEach(function (r) { if (r && r.id) used[r.id] = true; });
    raw.forEach(function (r) {
      if (!r || r.id) return;
      var base = slugify(r.name), id = base, n = 2;
      while (used[id]) id = base + '_' + n++;
      r.id = id; used[id] = true; dirty = true;
    });
    if (dirty) writeRaw(raw);
    return raw;
  }

  function published() {
    return (typeof YARA_RULES !== 'undefined' && Array.isArray(YARA_RULES)) ? YARA_RULES : [];
  }

  function all() {
    var pub = published().map(function (r) { return Object.assign({}, r, { _local: false }); });
    var pubIds = {};
    pub.forEach(function (r) { pubIds[r.id] = true; });
    // a local copy whose id is already published was committed — hide the duplicate
    var loc = localRaw()
      .filter(function (r) { return r && r.rule && !pubIds[r.id]; })
      .map(function (r) { return Object.assign({}, r, { _local: true }); });
    return loc.concat(pub).sort(function (a, b) { return (b.date || '').localeCompare(a.date || ''); });
  }

  function count() { return all().length; }

  function reportCount() {
    var n = 0;
    if (typeof REPORTS !== 'undefined') REPORTS.forEach(function (r) { n += (r.yara ? r.yara.length : 0); });
    return n;
  }

  function total() { return reportCount() + count(); }

  function uniqueId(base) {
    var taken = {};
    all().forEach(function (r) { taken[r.id] = true; });
    localRaw().forEach(function (r) { taken[r.id] = true; });
    var id = base, n = 2;
    while (taken[id]) id = base + '_' + n++;
    return id;
  }

  function addLocal(entry) {
    var raw = localRaw();
    raw.unshift(entry);
    return writeRaw(raw);
  }

  function removeLocal(id) {
    return writeRaw(localRaw().filter(function (r) { return r.id !== id; }));
  }

  function exportJs() {
    var entries = all().map(function (r) { var c = Object.assign({}, r); delete c._local; return c; });
    var head = [
      '// ============================================================',
      '//  YARA-DATA.JS — generated by detections.html on ' + new Date().toISOString().slice(0, 10),
      '//  Replace assets/js/yara-data.js with this file, then',
      '//  git add, git commit, git push.',
      '// ============================================================',
      '',
      'const YARA_RULES = '
    ].join('\n');
    return head + JSON.stringify(entries, null, 2) + ';\n';
  }

  window.YaraStore = {
    LS_KEY: LS_KEY,
    slugify: slugify,
    all: all,
    count: count,
    reportCount: reportCount,
    total: total,
    uniqueId: uniqueId,
    addLocal: addLocal,
    removeLocal: removeLocal,
    exportJs: exportJs
  };
})();
